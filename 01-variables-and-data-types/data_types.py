"""
Python Built-in Data Types
"""

# String
language = "Python"

# Integer
year = 2026

# Float
price = 19.99

# Boolean
is_online = True

# List
frameworks = ["Django", "FastAPI", "Flask"]

# Tuple
screen_size = (1920, 1080)

# Set
numbers = {1, 2, 3, 4, 5}

# Dictionary
user = {
    "username": "mohammadreza",
    "age": 23,
    "city": "Shiraz",
}

print(type(language))
print(type(year))
print(type(price))
print(type(is_online))
print(type(frameworks))
print(type(screen_size))
print(type(numbers))
print(type(user))